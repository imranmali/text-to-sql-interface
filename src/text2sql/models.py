"""Shared data models passed between pipeline stages and returned by the API."""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class Severity(StrEnum):
    """How serious a finding is. ``error`` findings block a query."""

    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


class Violation(BaseModel):
    """A single guardrail finding."""

    type: str = Field(description="Machine-readable violation code, e.g. 'prompt_injection'.")
    message: str = Field(description="Human-readable explanation.")
    severity: Severity = Severity.ERROR


class GuardrailResult(BaseModel):
    """Outcome of running a guardrail over an input or a SQL statement."""

    allowed: bool
    violations: list[Violation] = Field(default_factory=list)
    rewritten_sql: str | None = Field(
        default=None,
        description="SQL to execute instead of the original (e.g. with LIMIT enforced).",
    )

    @classmethod
    def ok(cls, rewritten_sql: str | None = None) -> GuardrailResult:
        return cls(allowed=True, rewritten_sql=rewritten_sql)

    @classmethod
    def blocked(cls, violations: list[Violation]) -> GuardrailResult:
        return cls(allowed=False, violations=violations)


class HallucinationIssue(BaseModel):
    """A grounding problem found in generated SQL or in its results."""

    type: str = Field(description="e.g. 'unknown_table', 'unknown_column', 'suspicious_join'.")
    message: str
    severity: Severity = Severity.ERROR
    reference: str | None = Field(default=None, description="The offending identifier.")
    suggestion: str | None = Field(default=None, description="Closest valid identifier.")


class HallucinationReport(BaseModel):
    """Grounding analysis of a SQL query."""

    issues: list[HallucinationIssue] = Field(default_factory=list)
    confidence: float = Field(ge=0.0, le=1.0, default=1.0)
    is_hallucinated: bool = False
    referenced_tables: list[str] = Field(default_factory=list)
    referenced_columns: list[str] = Field(default_factory=list)

    def feedback(self) -> list[str]:
        """Messages suitable for passing back to a generator for correction."""
        lines = []
        for issue in self.issues:
            line = issue.message
            if issue.suggestion:
                line += f" (did you mean '{issue.suggestion}'?)"
            lines.append(line)
        return lines


class SQLGeneration(BaseModel):
    """Output of an LLM provider."""

    sql: str | None = Field(default=None, description="Candidate SQL, or None if unanswerable.")
    explanation: str = ""
    provider: str = ""


class QueryResult(BaseModel):
    """Rows returned by the executor."""

    columns: list[str] = Field(default_factory=list)
    rows: list[list[Any]] = Field(default_factory=list)
    row_count: int = 0
    truncated: bool = False
    duration_ms: float = 0.0


class PipelineStatus(StrEnum):
    SUCCESS = "success"
    BLOCKED = "blocked"
    HALLUCINATION = "hallucination"
    UNANSWERABLE = "unanswerable"
    ERROR = "error"


class PipelineResponse(BaseModel):
    """Everything the pipeline knows about one question."""

    question: str
    status: PipelineStatus
    sql: str | None = Field(default=None, description="SQL as generated by the provider.")
    executed_sql: str | None = Field(default=None, description="SQL after guardrail rewrites.")
    explanation: str = ""
    provider: str = ""
    attempts: int = 0
    violations: list[Violation] = Field(default_factory=list)
    hallucination: HallucinationReport | None = None
    confidence: float | None = None
    result: QueryResult | None = None
    warnings: list[HallucinationIssue] = Field(default_factory=list)
    error: str | None = None
